static void render_char(SDL_Renderer* renderer, char c, int px, int py,
                        SDL_Color color, int scale) {
    if (c < 32 || c > 126) c = ' ';
    const uint8_t* glyph = FONT_5X7[c - 32];

    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);

    for (int col = 0; col < 5; ++col) {
        uint8_t line = glyph[col];
        for (int row = 0; row < 7; ++row) {
            if ((line >> row) & 1) {
                if (scale == 1) {
                    SDL_RenderDrawPoint(renderer, px + col, py + row);
                } else {
                    SDL_Rect r{px + col * scale, py + row * scale, scale, scale};
                    SDL_RenderFillRect(renderer, &r);
                }
            }
        }
    }
}

void FontRenderer::draw_text(SDL_Renderer* renderer, const std::string& text, int x, int y,
                            SDL_Color color, int scale, bool shadow) {
    int cur_x = x;
    int cur_y = y;
    int char_spacing = 6 * scale; // 5 pixels width + 1 pixel space
    int line_spacing = 9 * scale;

    if (shadow) {
        SDL_Color shadow_color{10, 12, 16, 180};
        draw_text(renderer, text, x + scale, y + scale, shadow_color, scale, false);
    }

    for (char c : text) {
        if (c == '\n') {
            cur_x = x;
            cur_y += line_spacing;
            continue;
        }
        render_char(renderer, c, cur_x, cur_y, color, scale);
        cur_x += char_spacing;
    }
}

void FontRenderer::draw_text_centered(SDL_Renderer* renderer, const std::string& text,
                                     int center_x, int y, SDL_Color color, int scale, bool shadow) {
    int w = get_text_width(text, scale);
    int start_x = center_x - w / 2;
    draw_text(renderer, text, start_x, y, color, scale, shadow);
}

int FontRenderer::get_text_width(const std::string& text, int scale) {
    size_t len = 0;
    size_t max_len = 0;
    for (char c : text) {
        if (c == '\n') {
            if (len > max_len) max_len = len;
            len = 0;
        } else {
            len++;
        }
    }
    if (len > max_len) max_len = len;
    return static_cast<int>(max_len) * 6 * scale;
}

int FontRenderer::get_text_height(int scale) {
    return 7 * scale;
}

